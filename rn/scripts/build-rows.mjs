// Build-time data prep: `node scripts/build-rows.mjs` (needs rsvg-convert: `brew install librsvg`).
// Writes src/data/rows.json (ready-to-render rows, day separators, grouping, "HH:MM"),
// and renders the bubble tails, ticks, play icon and voice waveforms to @3x PNGs
// from the exact SVG paths the app used to draw at runtime.
// Only the "today" date shift is left to runtime (it depends on the launch date).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const root = new URL('../src/data/', import.meta.url).pathname;
const msgs = JSON.parse(readFileSync(root + 'messages.json', 'utf8'));
const DAY = 86_400_000;
const pad = (n) => (n < 10 ? '0' + n : '' + n);

const rows = [];
const incoming = []; // row indices of their text messages (pool for the simulated incoming stream)
for (const m of msgs) {
  const ms = Date.parse(m.timestamp);
  const day = Math.floor(ms / DAY);
  const last = rows[rows.length - 1];
  let first = true;
  if (!last || last.day !== day) rows.push({ kind: 'day', key: 'd' + day, day });
  else if (last.kind === 'msg' && last.m.author === m.author) {
    first = false;
    last.tail = false;
  }
  const d = new Date(ms);
  const { timestamp, ...rest } = m;
  if (m.author === 'them' && m.type === 'text') incoming.push(rows.length);
  rows.push({ kind: 'msg', key: '' + m.id, m: rest, day, time: pad(d.getUTCHours()) + ':' + pad(d.getUTCMinutes()), first, tail: true });
}
writeFileSync(root + 'rows.json', JSON.stringify({ rows, incoming }));

// ---- static images (same paths/colors as the former react-native-svg components) ----
const ui = root + 'ui/';
const waves = root + 'waves/';
rmSync(waves, { recursive: true, force: true });
mkdirSync(ui, { recursive: true });
mkdirSync(waves, { recursive: true });
const png = (svg, out) => execFileSync('rsvg-convert', ['-z', '3', '-o', out], { input: svg });
const svg = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${body}</svg>`;

const TAIL = 'M0 0 C0 9 4 14 10 16 C5 16.6 2 16.2 0 15 Z';
png(svg(10, 16, `<path d="${TAIL}" fill="#D9FDD3"/>`), ui + 'tail-out@3x.png');
png(svg(10, 16, `<g transform="translate(10 0) scale(-1 1)"><path d="${TAIL}" fill="#FFFFFF"/></g>`), ui + 'tail-in@3x.png');
const TICKS = 'M1 6 L4.2 9.2 L11 1.5 M7.6 8.6 L8.4 9.2 L15.2 1.5';
for (const [name, color] of [['ticks-read', '#53BDEB'], ['ticks-white', '#FFFFFF']])
  png(svg(16, 11, `<path d="${TICKS}" stroke="${color}" stroke-width="1.5" fill="none" stroke-linecap="round" stroke-linejoin="round"/>`), ui + name + '@3x.png');
png(svg(20, 22, '<path d="M3 2.2 C3 1.1 4.1 .5 5 1 L18 9.8 C18.8 10.4 18.8 11.6 18 12.2 L5 21 C4.1 21.5 3 20.9 3 19.8 Z" fill="#54656F"/>'), ui + 'play@3x.png');

function bars(seed) {
  let d = '';
  let x = seed * 9301 + 49297;
  for (let i = 0; i < 30; i++) {
    x = (x * 9301 + 49297) % 233280;
    const h = 3 + (x / 233280) * 17;
    const px = 1.5 + i * 5;
    d += `M${px} ${12 - h / 2}V${12 + h / 2}`;
  }
  return d;
}
const voice = msgs.filter((m) => m.type === 'voice');
let ts = '// generated by scripts/build-rows.mjs\nexport const waves: Record<number, number> = {\n';
for (const m of voice) {
  const color = m.author === 'me' ? '#8FA89A' : '#B5BEC4';
  png(svg(150, 24, `<path d="${bars(m.id)}" stroke="${color}" stroke-width="2.4" stroke-linecap="round"/>`), `${waves}w${m.id}@3x.png`);
  ts += `  ${m.id}: require('./waves/w${m.id}.png'),\n`;
}
writeFileSync(root + 'waves.ts', ts + '};\n');
console.log(`rows ${rows.length}, incoming pool ${incoming.length}, waveforms ${voice.length}`);
